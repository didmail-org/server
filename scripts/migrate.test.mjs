import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { migrate } from './migrate.mjs';
import { walletType } from './setup.mjs';
const require = createRequire(import.meta.url);
const sqlite3 = require('sqlite3');
const { fromRandom, fromSecretKey } = require('@ocap/wallet');
const query = (db, sql) => new Promise((resolve, reject) => db.all(sql, (e, rows) => e ? reject(e) : resolve(rows)));
const close = db => new Promise((resolve, reject) => db.close(e => e ? reject(e) : resolve()));

test('copies a WAL snapshot and preserves the node identity, ciphertext and source', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'didmail-import-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const source = path.join(dir, 'source.sqlite');
  const keyFile = path.join(dir, 'wallet.json');
  const destination = path.join(dir, 'destination');
  const targetWallet = path.join(destination, 'node-wallet.json');
  const original = fromRandom(walletType);
  fs.writeFileSync(keyFile, JSON.stringify({ address: original.address, secretKey: original.secretKey }));
  const db = new sqlite3.Database(source);
  await query(db, 'PRAGMA journal_mode=WAL');
  await query(db, 'CREATE TABLE mails (id INTEGER PRIMARY KEY, content BLOB)');
  await query(db, "INSERT INTO mails VALUES (1, x'0100ff')");
  await query(db, 'CREATE TABLE domain_bindings (domainKeyEnc TEXT)');
  await query(db, "INSERT INTO domain_bindings VALUES ('opaque-encrypted-domain-key')");
  const report = await migrate({ source, keyFile, destination, targetWallet, expectedAddress: original.address });
  assert.equal(report.integrity, 'ok');
  assert.deepEqual(report.counts, { domain_bindings: 1, mails: 1 });
  const imported = JSON.parse(fs.readFileSync(targetWallet, 'utf8'));
  assert.equal(fromSecretKey(imported.secretKey, walletType).address, original.address);
  assert.equal(fs.statSync(targetWallet).mode & 0o777, 0o600);
  const copy = new sqlite3.Database(path.join(destination, 'didmail.sqlite'));
  assert.deepEqual((await query(copy, 'SELECT content FROM mails'))[0].content, Buffer.from([1, 0, 255]));
  assert.equal((await query(copy, 'SELECT domainKeyEnc FROM domain_bindings'))[0].domainKeyEnc, 'opaque-encrypted-domain-key');
  await close(copy);
  assert.equal((await query(db, 'SELECT COUNT(*) AS count FROM mails'))[0].count, 1);
  await assert.rejects(migrate({ source, keyFile, destination, targetWallet }), /exists/);
  await assert.rejects(migrate({ source, keyFile, destination: path.join(dir, 'wrong'), targetWallet: path.join(dir, 'wrong/key.json'), expectedAddress: 'wrong-node' }), /does not match/);
  await close(db);
});

test('rejects unrelated databases without leaving a target wallet or database', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'didmail-invalid-import-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const source = path.join(dir, 'source.sqlite');
  const db = new sqlite3.Database(source);
  await query(db, 'CREATE TABLE unrelated (value TEXT)');
  await close(db);
  const keyFile = path.join(dir, 'wallet.json');
  fs.writeFileSync(keyFile, JSON.stringify({ secretKey: fromRandom(walletType).secretKey }));
  const destination = path.join(dir, 'new');
  const targetWallet = path.join(destination, 'node-wallet.json');
  await assert.rejects(migrate({ source, keyFile, destination, targetWallet }), /mails table missing/);
  assert.equal(fs.existsSync(targetWallet), false);
  assert.equal(fs.existsSync(path.join(destination, 'didmail.sqlite')), false);
});
